function buildZone(
  id: string,
  code: string,
  name: string,
  category: string,
  accent: ZoneBreakdownItem['accent'],
  predicate: (bay: ParkingBay) => boolean,
): ZoneBreakdownItem {
  const subset = BAYS.filter(predicate)
  return {
    id,
    code,
    name,
    category,
    occupied: subset.filter((b) => b.status === 'occupied').length,
    reserved: subset.filter((b) => b.status === 'reserved').length,
    unavailable: subset.filter((b) => b.status === 'unavailable').length,
    capacity: subset.length,
    accent,
  }
}

